let a = 10;
let b = 5;
console.log(a+b); //15
console.log(a-b); //5
console.log(a*b);  //50
console.log(a/b);  //2
console.log(a%b);  //0
console.log(a**b);  //100000 Exponential
console.log(a++);  //10  post Increment
console.log(++a);  //12   pre Increment
console.log(a--);   //12   post decrement
console.log(--a);    //10  pre decrement
