function isEven(num) {  
  if (num % 2 === 0) {
        return "Even";
    } else {
        return "Odd";
   }  
}
console.log(isEven(10)); // Output: Even
console.log(isEven(7));  // Output: Odd
console.log(isEven(0));  // Output: Even
console.log(isEven(-3)); // Output: Odd
console.log(isEven(-4)); // Output: Even





